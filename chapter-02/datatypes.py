# BASIC DATA TYPES IN PYTHON

a = "sonali"  # a is a string
b = 55        # b is an integer
c = 6.9       # c is a floating-point number
d = True      # d is a Boolean value
e = None      # e represents the absence of a value

print(type(a))
print(type(b))
print(type(c))
print(type(d))
print(type(e))


# Python is a dynamically typed language.
# It automatically determines the data type of a value based on
# the value assigned to a variable.

# Common basic data types include:
# str   → Stores text/string values
# int   → Stores whole numbers
# float → Stores decimal numbers
# bool  → Stores True or False values
# NoneType → Represents the absence of a value