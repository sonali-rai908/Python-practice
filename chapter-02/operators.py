# OPERATORS IN PYTHON

# 1. ARITHMETIC OPERATORS
# Arithmetic operators are used to perform mathematical operations.
# Examples: +, -, *, /, %, **, //

a = 3
b = 4

print(a + b)  # Addition
print(a - b)  # Subtraction
print(a / b)  # Division
print(a * b)  # Multiplication


# 2. ASSIGNMENT OPERATORS
# Assignment operators are used to assign or update values of variables.
# Examples: =, +=, -=, *=, /=, etc.

c = 4 - 3  # Assigns the result of 4 - 3 to c
print(c)

d = 5

d += 3  # Adds 3 to the current value of d and stores the result back in d
print(d)

d -= 2  # Subtracts 2 from the current value of d and stores the result back in d
print(d)


# 3. COMPARISON OPERATORS
# Comparison operators are used to compare two values.
# They return either True or False.
# Examples: ==, >, <, >=, <=, !=

e = 7
f = 6

print(e == f)  # Checks whether e and f are equal
print(e <= f)  # Checks whether e is less than or equal to f
print(e >= f)  # Checks whether e is greater than or equal to f

g = "sonali"

# Different data types can also be compared for equality or inequality.
print(g == e)  # Checks whether g and e are equal
print(g != e)  # Checks whether g and e are not equal


# 4. LOGICAL OPERATORS
# Logical operators are used to combine or modify conditions.
# Examples: and, or, not

# and → Returns True only when both conditions are True.
# or  → Returns True when at least one condition is True.
# not → Reverses the Boolean value (True becomes False and vice versa).