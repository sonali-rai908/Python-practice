# TYPE() FUNCTION
# The type() function is used to check and display the data type of a value
# or variable.

a = 7

print(type(a))  # Displays the data type of a, which is int


# TYPE CASTING
# Type casting is used to convert a value from one data type to another.
#
# Common type conversion functions include:
# int()   → Converts a value to an integer
# float() → Converts a value to a floating-point number
# str()   → Converts a value to a string

b = str(a)  # Converts the integer value of a into a string

print(type(b))  # Displays the data type of b, which is str